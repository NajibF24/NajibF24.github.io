export type BrandName = keyof typeof brands;

// Keyword → brand, checked in order against a label such as "ArgoCD + ApplicationSets".
// Labels with no match (AWS, SQL Server, PowerShell, Gitleaks… not in simple-icons) get no icon.
const rules: [RegExp, BrandName][] = [
  [/gitlab/i, 'gitlab'],
  [/github/i, 'github'],
  [/argo/i, 'argo'],
  [/terraform/i, 'terraform'],
  [/helm/i, 'helm'],
  [/trivy/i, 'trivy'],
  [/sonar/i, 'sonarqube'],
  [/\bzap\b/i, 'zap'],
  [/harbor/i, 'harbor'],
  [/openbao|vault/i, 'openbao'],
  [/kubernetes|\beks\b|\bk8s\b/i, 'kubernetes'],
  [/rke2|rancher/i, 'rancher'],
  [/docker|buildkit/i, 'docker'],
  [/elastic/i, 'elastic'],
  [/grafana/i, 'grafana'],
  [/prometheus/i, 'prometheus'],
  [/victoria/i, 'victoriametrics'],
  [/fluent/i, 'fluentbit'],
  [/postgres|pgbackrest|pl\/pgsql|patroni/i, 'postgresql'],
  [/mariadb/i, 'mariadb'],
  [/redis/i, 'redis'],
  [/etcd/i, 'etcd'],
  [/cloudflare/i, 'cloudflare'],
  [/\bf5\b/i, 'f5'],
  [/fastapi/i, 'fastapi'],
  [/celery/i, 'celery'],
  [/fastify/i, 'fastify'],
  [/three\.?js/i, 'threejs'],
  [/socket\.?io/i, 'socketio'],
  [/node/i, 'nodejs'],
  [/typescript/i, 'typescript'],
  [/react/i, 'react'],
  [/python/i, 'python'],
  [/\bgo\b/i, 'go'],
  [/bash/i, 'bash'],
  [/claude/i, 'claude'],
  [/whatsapp/i, 'whatsapp'],
];

export function brandFor(label: string): BrandName | undefined {
  return rules.find(([re]) => re.test(label))?.[1];
}
